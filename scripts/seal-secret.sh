#!/usr/bin/env bash
# Encrypts the orders API key for one environment into a values file that is safe to commit.
#   scripts/seal-secret.sh dev   -> deploy/values/orders/secrets-dev.yaml
# Only the Sealed Secrets controller in THIS cluster can decrypt it. If you delete the
# cluster, the key is gone too: re-run this script (or back up the controller key, see the docs).
set -euo pipefail
cd "$(dirname "$0")/.."
ENV="${1:?usage: seal-secret.sh <dev|prod>}"
NS="shop-${ENV}"
OUT="deploy/values/orders/secrets-${ENV}.yaml"

if [[ -n "${API_KEY:-}" ]]; then
  key="$API_KEY"
else
  key="$(openssl rand -hex 24)"
  echo "Generated a random API key for ${ENV}: ${key}"
  echo "(save it: you need it in the X-API-Key header)"
fi

# --scope strict binds the ciphertext to this namespace AND this secret name ("orders"),
# so it can't be copied into another namespace and decrypted there.
cipher="$(printf '%s' "$key" | kubeseal --raw --scope strict \
  --namespace "$NS" --name orders \
  --controller-namespace kube-system --controller-name sealed-secrets-controller)"

cat > "$OUT" <<YAML
# Generated by scripts/seal-secret.sh. Encrypted, so safe to commit.
sealedSecret:
  enabled: true
  encryptedData:
    API_KEY: ${cipher}
YAML
echo "wrote $OUT"
